def words(title, name):
    t = title.replace(name, " ")
    t = re.sub(r"\[[^\]]*\]|\([^)]*\)|[‘’'\"“”…·,.!?%↑↓→\-/~:;<>|]|\d+(?:\.\d+)?(?![가-힣A-Za-z])", " ", t)
    out = []
    for w in t.split():
        if w in STOP or (w[:1].isdigit() and not re.fullmatch(r"\d+차전지|\dG", w)):
            continue                          # 숫자로 시작하는 토큰(1분기·0억·8월)은 버림. 2차전지·5G만 살림
        if not w.endswith(("유가", "국가")):    # 국제유가가 '국제유'로 잘리지 않게
            w = PARTICLE.sub("", w)
        if w.endswith("株") and len(w) >= 3:
            w = w[:-1]
        elif w.endswith("주") and len(w) >= 4 and w[:-1] not in ("휴머노이",):
            w = w[:-1]
        if len(w) >= 2 and w not in STOP and w not in name and not re.fullmatch(r"[A-Za-z]{1,2}", w):
            out.append(w)
    return out


def top_keywords(titles, name, stock_names, k=3):
    """titles: 그날 창 안의 기사 제목들 → [(키워드, 등장 기사 수)] 상위 k (2건 이상만)"""
    c = Counter()
    for t in titles:
        c.update({w for w in words(t, name) if w not in stock_names})
    return [(w, n) for w, n in c.most_common(k) if n >= 2]


def news_groups(stock_kw, min_stocks=2):
    """stock_kw: {code: [(kw, n), ...]} → {kw: [codes]} (각 종목 상위 2 키워드 기준, 2종목↑)"""
    g = {}
    for code, kws in stock_kw.items():
        for w, _ in kws[:2]:
            g.setdefault(w, []).append(code)
    return {w: cs for w, cs in g.items() if len(cs) >= min_stocks}
